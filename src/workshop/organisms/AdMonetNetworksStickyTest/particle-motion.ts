type ParticleMotion = ComponentProps<typeof OrbitParticles>['textured'][number]['motion'];

type MotionPoint = ParticleMotion['idle'][number];

function interpolateCoordinate(before: number, start: number, end: number, after: number, time: number) {
	const startSlope = (end - before) / 2;
	const endSlope = (after - start) / 2;
	return start + time * (startSlope + time * (
		3 * (end - start) - 2 * startSlope - endSlope
		+ time * (2 * (start - end) + startSlope + endSlope)
	));
}

function smoothFloat(points: MotionPoint[]): MotionPoint[] {
	const samples = points.slice(0, -1);
	const angleStep = 2 * Math.PI / samples.length;
	let cosineX = 0;
	let sineX = 0;
	let cosineY = 0;
	let sineY = 0;

	samples.forEach(([x, y], index) => {
		const angle = index * angleStep;
		cosineX += x * Math.cos(angle);
		sineX += x * Math.sin(angle);
		cosineY += y * Math.cos(angle);
		sineY += y * Math.sin(angle);
	});

	const [startX, startY] = points[0];
	// Keep the main oscillation and reduce its travel around the entry position.
	const amplitude = .6;
	const scale = 2 * amplitude / samples.length;
	return points.map((_, index) => {
		const angle = index * angleStep;
		const cosine = Math.cos(angle) - 1;
		const sine = Math.sin(angle);
		return [
			startX + scale * (cosineX * cosine + sineX * sine),
			startY + scale * (cosineY * cosine + sineY * sine),
		];
	});
}

export function smoothIdleLoop<T extends { motion: ParticleMotion }>(particle: T) {
	const source = particle.motion.idle;
	const first = source[0];
	const last = source[source.length - 1];
	const closureSamples = 4;
	// Spread the closing offset over the final samples instead of snapping on repeat.
	const closedPoints = source.map(([x, y], index): MotionPoint => {
		const time = Math.max(0, 1 - (source.length - 1 - index) / closureSamples);
		const weight = time * time * (3 - 2 * time);
		return [x + (first[0] - last[0]) * weight, y + (first[1] - last[1]) * weight];
	});
	const points = smoothFloat(closedPoints);
	points[0] = first;
	points[points.length - 1] = first;
	const samplesPerSegment = 6;
	const idle = points.slice(0, -1).flatMap((start, index) => {
		const before = points[index - 1] ?? points[points.length - 2];
		const end = points[index + 1];
		const after = points[index + 2] ?? points[1];

		return Array.from({ length: samplesPerSegment }, (_, sample): MotionPoint => {
			const time = sample / samplesPerSegment;
			return [
				interpolateCoordinate(before[0], start[0], end[0], after[0], time),
				interpolateCoordinate(before[1], start[1], end[1], after[1], time),
			];
		});
	});
	idle.push(points[points.length - 1]);

	const exitStart = particle.motion.exit[0];
	const exit = particle.motion.exit.map(([x, y], index): MotionPoint => {
		const time = Math.max(0, 1 - index / closureSamples);
		const weight = time * time * (3 - 2 * time);
		return [x + (first[0] - exitStart[0]) * weight, y + (first[1] - exitStart[1]) * weight];
	});
	exit[0] = first;

	return { ...particle, motion: { ...particle.motion, idle, exit } };
}

